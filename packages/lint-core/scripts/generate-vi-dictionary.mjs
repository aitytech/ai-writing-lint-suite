import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

// dictionary-vi's own index.js loads its .aff/.dic via node:fs at runtime -- Node-only,
// breaks in Cloudflare Workers (no filesystem) and needs bundler-specific asset config in
// Vite/Wrangler otherwise. Sidestepped entirely by inlining both files' content as plain TS
// string constants at build time: the result is ordinary JS/TS source with zero
// bundler-specific import syntax, so it just works identically in Node, Workers, and Vite
// with no module-rule configuration anywhere (unlike Suzume's .wasm, which genuinely can't
// be inlined this way -- these are small (~44KB total) UTF-8 text files, not WASM). Run via
// the "predictionary" build script; committed output, not gitignored, so a fresh clone
// doesn't need this script to have run to type-check.
const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);

// dictionary-vi's package.json only declares "exports": "./index.js" (no "./package.json"
// subpath), so require.resolve("dictionary-vi/package.json") fails under strict ESM exports
// resolution -- resolve the main entry instead and derive the package dir from that.
const dictDir = dirname(require.resolve("dictionary-vi"));
const aff = readFileSync(join(dictDir, "index.aff"), "utf8");
const dic = readFileSync(join(dictDir, "index.dic"), "utf8");
const dictVersion = JSON.parse(readFileSync(join(dictDir, "package.json"), "utf8")).version;

const out = `// GENERATED by scripts/generate-vi-dictionary.mjs from dictionary-vi@${dictVersion}
// -- do not hand-edit, re-run the script instead.
export const viDictionaryAff = ${JSON.stringify(aff)};
export const viDictionaryDic = ${JSON.stringify(dic)};
`;

writeFileSync(join(here, "..", "src", "vi-dictionary-data.ts"), out);
console.log(`Generated src/vi-dictionary-data.ts (${aff.length + dic.length} chars inlined)`);
