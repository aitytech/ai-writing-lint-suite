import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

// Same inlining pattern as generate-vi-dictionary.mjs (see that file's own comment for the
// full "why" -- Node-only fs reads inside dictionary-en's own loader, breaks on Workers,
// sidestepped by inlining as plain TS string constants instead of a runtime file read).
// dictionary-en's .dic is much bigger than dictionary-vi's (~550KB vs ~44KB) since English has
// a larger base vocabulary than this Vietnamese wordlist -- still small next to Harper's ~8MB
// WASM, and text compresses well under gzip (checked directly against the built worker.js
// bundle before relying on "should be fine", see mcp-server/README.md).
const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);

const dictDir = dirname(require.resolve("dictionary-en"));
const aff = readFileSync(join(dictDir, "index.aff"), "utf8");
const dic = readFileSync(join(dictDir, "index.dic"), "utf8");
const dictVersion = JSON.parse(readFileSync(join(dictDir, "package.json"), "utf8")).version;

const out = `// GENERATED by scripts/generate-en-dictionary.mjs from dictionary-en@${dictVersion}
// -- do not hand-edit, re-run the script instead.
export const enDictionaryAff = ${JSON.stringify(aff)};
export const enDictionaryDic = ${JSON.stringify(dic)};
`;

writeFileSync(join(here, "..", "src", "en-dictionary-data.ts"), out);
console.log(`Generated src/en-dictionary-data.ts (${aff.length + dic.length} chars inlined)`);
